import assert from "node:assert/strict";
import {mergeRings, savedPrefix, restoreSession} from "../web/session.mjs";

const first={stage:1,x:8000,y:8000,r:4800};
const second={stage:2,x:8500,y:8000,r:2300};
const third={stage:3,x:8500,y:8100,r:1457};
const initial=[{...first}];
const two=mergeRings(initial,[second]);
assert.deepEqual(two,[first,second]);
assert.deepEqual(initial,[first]);
assert.deepEqual(mergeRings(two,[third]),[first,second,third]);
assert.deepEqual(mergeRings([],[second,first]),[first,second]);
assert.throws(()=>mergeRings(initial,[third]),/不能跳过/);
assert.throws(()=>mergeRings(initial,[second,second]),/重复/);
assert.throws(()=>mergeRings(initial,[first]),/已保存/);
assert.throws(()=>mergeRings(initial,[{...second,x:15000}]),/没有包含/);
assert.throws(()=>mergeRings(initial,[{...second,r:5000}]),/没有包含/);
assert.throws(()=>mergeRings(initial,[{...second,stage:4}]),/无效/);
assert.throws(()=>mergeRings(initial,[]),/至少/);
assert.deepEqual(initial,[first]);
const saved={version:1,count:2,rings:[first,second,{}]};
assert.deepEqual(savedPrefix(restoreSession(JSON.stringify(saved)).rings),[first,second]);
assert.equal(restoreSession("broken"),null);
assert.equal(restoreSession(JSON.stringify({...saved,version:99})),null);
assert.equal(restoreSession(JSON.stringify({...saved,count:4})),null);
assert.equal(restoreSession(JSON.stringify({...saved,rings:[first]})),null);
assert.deepEqual(savedPrefix([first,{},third]),[first]);
assert.deepEqual(savedPrefix(restoreSession(JSON.stringify({...saved,rings:[first,{x:-1,y:8000,r:2300},{}]})).rings),[first]);
console.log("Match session checks passed: incremental stages, no overwrite, nesting, atomic failure, and refresh restoration.");
